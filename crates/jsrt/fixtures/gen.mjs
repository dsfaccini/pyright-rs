// Generates jsrt's node-derived fixtures and tables. Node is the oracle: run
// this with Node 26 (the runtime pyright runs on), then commit the output.
//
//   node crates/jsrt/fixtures/gen.mjs [section...]
//
// Sections: tables, strings, normalize, numbers, bigints, sort, regex, arrays. No argument runs all.
// Every random input comes from a seeded PRNG, so a rerun gives the same files.

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const crate = dirname(here);

if (process.versions.node.split('.')[0] !== '26') {
    throw new Error(`expected Node 26, got ${process.versions.node}`);
}

// mulberry32: 32-bit seeded PRNG.
function rng(seed) {
    let a = seed >>> 0;
    const next = () => {
        a = (a + 0x6d2b79f5) >>> 0;
        let t = a;
        t = Math.imul(t ^ (t >>> 15), t | 1);
        t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
        return (t ^ (t >>> 14)) >>> 0;
    };
    next.int = (n) => next() % n;
    next.pick = (arr) => arr[next() % arr.length];
    return next;
}

// A JS string as an array of UTF-16 code units: JSON can't carry a lone
// surrogate to Rust's serde_json.
const u = (s) => Array.from({ length: s.length }, (_, i) => s.charCodeAt(i));

// One array element per line keeps the diffs readable.
function dump(file, obj) {
    const parts = Object.entries(obj).map(([key, value]) => {
        const body = Array.isArray(value)
            ? '[\n' + value.map((v) => JSON.stringify(v)).join(',\n') + '\n]'
            : JSON.stringify(value);
        return `${JSON.stringify(key)}: ${body}`;
    });
    writeFileSync(join(here, file), '{\n' + parts.join(',\n') + '\n}\n');
    console.log(`wrote fixtures/${file}`);
}

const MAX_CP = 0x10ffff;
const charOf = (cp) => String.fromCodePoint(cp);

// Every code point, with each surrogate as a lone code unit.
function* allCodePoints() {
    for (let cp = 0; cp <= MAX_CP; cp++) yield cp;
}

function ranges(pred) {
    const out = [];
    let start = -1;
    for (let cp = 0; cp <= MAX_CP + 1; cp++) {
        const inSet = cp <= MAX_CP && pred(cp);
        if (inSet && start < 0) start = cp;
        if (!inSet && start >= 0) {
            out.push([start, cp - 1]);
            start = -1;
        }
    }
    return out;
}

function tables() {
    const cased = /^\p{Cased}$/u;
    const ignorable = /^\p{Case_Ignorable}$/u;
    const fmt = (rs) => rs.map(([a, b]) => `    (0x${a.toString(16).toUpperCase()}, 0x${b.toString(16).toUpperCase()}),`).join('\n');
    const src = `//! Generated by \`fixtures/gen.mjs\` from Node ${process.versions.node} (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}). Do not edit.

/// Code point ranges with the Unicode property Cased.
pub(super) const CASED: &[(u32, u32)] = &[
${fmt(ranges((cp) => cased.test(charOf(cp))))}
];

/// Code point ranges with the Unicode property Case_Ignorable.
pub(super) const CASE_IGNORABLE: &[(u32, u32)] = &[
${fmt(ranges((cp) => ignorable.test(charOf(cp))))}
];
`;
    writeFileSync(join(crate, 'src/string/case_tables.rs'), src);
    console.log('wrote src/string/case_tables.rs');
}

// Characters that make string methods disagree between UTF-8, UTF-16 and JS:
// astral chars, chars above the surrogates, whitespace of both kinds, case
// specials, `$` patterns and lone surrogates.
const POOL = [
    'a', 'b', 'A', 'Z', '0', '9', ' ', '$', '&', '`', "'", '<', '>', '-', '.',
    '\t', '\n', '\r', '\v', '\f', ' ', '\u0085', ' ', ' ', ' ', ' ', '　', '﻿', '᠎', '​',
    'é', 'ß', 'İ', 'ı', 'Σ', 'σ', 'ς', 'ͅ', '̀', '­', 'ʰ', 'ᾈ', 'ŉ', 'ﬁ',
    '', '￿', 'Ａ', '퟿',
    '\u{1f600}', '\u{10400}', '\u{10428}', '\u{1d400}', '\u{20000}',
    '\ud800', '\udc00', '\udbff', '\udfff',
];

function randomString(r, maxLen, pool = POOL) {
    const n = r.int(maxLen + 1);
    let s = '';
    for (let i = 0; i < n; i++) s += r.pick(pool);
    return s;
}

const isWellFormed = (s) => s.isWellFormed();
const optIndex = (r, len) => (r.int(5) === 0 ? null : r.int(2 * len + 7) - len - 3);

function strings() {
    const whitespace = [];
    for (let unit = 0; unit <= 0xffff; unit++) {
        if (String.fromCharCode(unit).trim() === '') whitespace.push(unit);
    }
    for (let cp = 0x10000; cp <= MAX_CP; cp++) {
        if (charOf(cp).trim() === '') throw new Error(`astral whitespace ${cp}`);
    }

    const lower = [];
    const upper = [];
    for (const cp of allCodePoints()) {
        const s = charOf(cp);
        if (s.toLowerCase() !== s) lower.push([cp, u(s.toLowerCase())]);
        if (s.toUpperCase() !== s) upper.push([cp, u(s.toUpperCase())]);
    }

    const r = rng(1);
    const casePool = [
        'Σ', 'Σ', 'Σ', 'a', 'A', '1', ' ', '.', "'", 'ͅ', '­', '̀', 'ʰ', 'ᾈ', '‘',
        '\u{10400}', '\u{10428}', '\u{1e900}', 'İ', 'ß', '\ud800', '\udc00', '　', 'א', '·', '·',
        '\u{1f600}', '\u{e0001}', '\u{1d41a}',
    ];
    const caseContexts = [];
    for (let i = 0; i < 4000; i++) {
        const s = randomString(r, 8, casePool);
        caseContexts.push([u(s), u(s.toLowerCase()), u(s.toUpperCase())]);
    }

    const json = [];
    for (let unit = 0; unit <= 0xffff; unit++) {
        const s = String.fromCharCode(unit);
        if (JSON.stringify(s) !== `"${s}"`) json.push([unit, JSON.stringify(s)]);
    }
    for (let i = 0; i < 500; i++) {
        const s = randomString(r, 10);
        json.push([u(s), u(JSON.stringify(s))]);
    }

    const cmp = [];
    for (let i = 0; i < 2000; i++) {
        const a = randomString(r, 4);
        const b = r.int(3) === 0 ? a + randomString(r, 2) : randomString(r, 4);
        cmp.push([u(a), u(b), a < b ? -1 : a > b ? 1 : 0]);
    }

    const index = [];
    for (let i = 0; i < 3000; i++) {
        const s = randomString(r, 8);
        const a = r.int(2 * s.length + 7) - s.length - 3;
        const b = optIndex(r, s.length);
        const bArg = b ?? undefined;
        index.push({
            s: u(s), a, b,
            slice: u(s.slice(a, bArg)),
            substring: u(s.substring(a, bArg)),
            substr: u(s.substr(a, bArg)),
            charCodeAt: Number.isNaN(s.charCodeAt(a)) ? null : s.charCodeAt(a),
            codePointAt: s.codePointAt(a) ?? null,
        });
    }

    const search = [];
    for (let i = 0; i < 4000; i++) {
        const s = randomString(r, 10);
        let t;
        const mode = r.int(4);
        if (mode === 0 && s.length > 0) {
            const x = r.int(s.length + 1);
            t = s.slice(x, x + r.int(4));
        } else if (mode === 1) {
            t = '';
        } else {
            t = randomString(r, 2);
        }
        const p = r.int(2 * s.length + 7) - s.length - 3;
        const q = optIndex(r, s.length);
        const qArg = q ?? undefined;
        search.push({
            s: u(s), t: u(t), p, q,
            indexOf: s.indexOf(t, p),
            lastIndexOf: s.lastIndexOf(t, qArg),
            includes: s.includes(t, p),
            startsWith: s.startsWith(t, p),
            endsWith: s.endsWith(t, qArg),
        });
    }

    const split = [];
    for (let i = 0; i < 2000; i++) {
        const s = randomString(r, 10, ['a', 'b', ',', ',', ' ', '\u{1f600}', '\ud800', 'é']);
        const sep = r.pick(['', ',', ', ', 'a', 'ab', '\u{1f600}', '\ud83d', 'zz', ',,']);
        const limit = r.int(3) === 0 ? null : r.int(6);
        split.push({ s: u(s), sep: u(sep), limit, out: s.split(sep, limit ?? undefined).map(u) });
    }

    const replace = [];
    const templatePool = ['$', '$', '$$', '$&', '$`', "$'", '$1', '$01', '$<x>', 'x', 'é', '\u{1f600}', '$0'];
    for (let i = 0; i < 3000; i++) {
        const s = randomString(r, 8, ['a', 'b', 'c', '$', 'é', '\u{1f600}', '\ud800']);
        const pat = r.int(5) === 0 ? '' : randomString(r, 2, ['a', 'b', 'c', '$', 'é', '\u{1f600}']) || 'a';
        const rep = randomString(r, 4, templatePool);
        replace.push({ s: u(s), pat: u(pat), rep: u(rep), replace: u(s.replace(pat, rep)), replaceAll: u(s.replaceAll(pat, rep)) });
    }

    const trim = [];
    for (let i = 0; i < 1000; i++) {
        const s = randomString(r, 8);
        trim.push([u(s), u(s.trim()), u(s.trimStart()), u(s.trimEnd())]);
    }

    dump('strings.json', { whitespace, lower, upper, caseContexts, json, cmp, index, search, split, replace, trim });
}

const FORMS = ['NFC', 'NFD', 'NFKC', 'NFKD'];

function normalize() {
    const single = Object.fromEntries(FORMS.map((f) => [f, []]));
    for (const cp of allCodePoints()) {
        const s = charOf(cp);
        for (const f of FORMS) {
            const n = s.normalize(f);
            if (n !== s) single[f].push([cp, u(n)]);
        }
    }

    // Each code point next to a mark of the lowest (U+0334, ccc 1) and the
    // highest (U+0345, ccc 240) combining class. A code point with a non-zero
    // class moves past one of them.
    const LOW = '̴';
    const HIGH = 'ͅ';
    const context = { NFC: [], NFD: [] };
    const marks = [];
    for (const cp of allCodePoints()) {
        const s = charOf(cp);
        let moved = false;
        for (const f of ['NFC', 'NFD']) {
            const after = (s + LOW).normalize(f);
            const before = (HIGH + s).normalize(f);
            const plainAfter = s.normalize(f) + LOW;
            const plainBefore = HIGH + s.normalize(f);
            if (after !== plainAfter || before !== plainBefore) {
                context[f].push([cp, u(after), u(before)]);
            }
            if (f === 'NFD' && s.normalize('NFD') === s && (after === LOW + s || before === s + HIGH)) moved = true;
        }
        if (moved || cp === 0x0334 || cp === 0x0345) marks.push(cp);
    }

    // Rank the marks by combining class: a sorts after b when NFD reorders a+b.
    const reorders = (a, b) => (charOf(a) + charOf(b)).normalize('NFD') === charOf(b) + charOf(a);
    const sorted = [...marks].sort((a, b) => (reorders(a, b) ? 1 : reorders(b, a) ? -1 : 0));
    const ranks = [];
    let rank = 0;
    for (let i = 0; i < sorted.length; i++) {
        if (i > 0 && reorders(sorted[i], sorted[i - 1])) rank++;
        ranks.push([sorted[i], rank]);
    }
    for (let i = 1; i < sorted.length; i++) {
        if (reorders(sorted[i - 1], sorted[i])) throw new Error('mark ranking is not a total preorder');
    }

    const r = rng(2);
    const starters = [
        ...'AEIOUaeiouCcNnSsLlRrZzGgHhKkWwYy<=>',
        'α', 'ω', 'η', 'и', 'е', 'א', 'ا', 'क', 'େ', 'ෙ', 'ဥ', 'う', 'ハ',
        'ᄀ', 'ᄒ', 'ᅡ', 'ᅵ', 'ᆨ', 'ᇂ', 'ᆧ', 'ᅠ', '가', '각', '힣', 'ㄱ',
        'é', 'ǖ', 'ḱ', 'क़', 'Å', '̈́', 'ཱི', '\u{1109a}', '\u{11131}', '\u{1d15e}',
        'ﬁ', '①', '㈱', 'Ａ', 'ẛ', 'ﷺ', ' ', 'Ω', 'ΐ', 'ᾀ', 'ཷ',
        '\ud800', '\udc00', '\u{1f600}',
    ];
    const markChars = marks.map(charOf);
    const pool = [...starters, ...starters, ...markChars.slice(0, 64), ...markChars];
    const random = [];
    for (let i = 0; i < 6000; i++) {
        let s = '';
        const n = 1 + r.int(7);
        for (let j = 0; j < n; j++) s += r.int(3) === 0 ? r.pick(starters) : r.pick(pool);
        random.push([u(s), ...FORMS.map((f) => u(s.normalize(f)))]);
    }

    dump('normalize.json', { ...Object.fromEntries(FORMS.map((f) => [`single${f}`, single[f]])), contextNFC: context.NFC, contextNFD: context.NFD, ranks, random });
}

// Sort inputs and comparators. tests/sort.rs mirrors SORT_MODES and
// SORT_KINDS exactly, with the same PRNG, so the fixture stores only seeds and
// fingerprints of V8's comparator calls.
const SORT_MODES = {
    random2: (r, n) => Array.from({ length: n }, () => r.int(2)),
    random10: (r, n) => Array.from({ length: n }, () => r.int(10)),
    randomN: (r, n) => Array.from({ length: n }, () => r.int(n)),
    randomBig: (r, n) => Array.from({ length: n }, () => r()),
    sorted: (r, n) => Array.from({ length: n }, (_, i) => i),
    reversed: (r, n) => Array.from({ length: n }, (_, i) => n - i),
    runs: (r, n) => {
        const out = [];
        while (out.length < n) {
            const len = 1 + r.int(200);
            const start = r.int(1000);
            const desc = r.int(2) === 1;
            for (let i = 0; i < len && out.length < n; i++) out.push(desc ? start - i : start + i);
        }
        return out;
    },
    sawtooth: (r, n) => {
        const k = 1 + r.int(50);
        return Array.from({ length: n }, (_, i) => i % k);
    },
};

const SORT_KINDS = {
    consistent: (a, b) => a - b,
    descending: (a, b) => b - a,
    random: (a, b, rc) => (rc() % 3) - 1,
    rockPaperScissors: (a, b) => [0, 1, -1][(((a - b) % 3) + 3) % 3],
    // types.ts sortTypes-like: two "literals" (odd values) always return 1.
    literalsReturnOne: (a, b) => (a & 1 && b & 1 ? 1 : a - b),
    fractionOrNaN: (a, b) => (a % 7 === b % 7 ? NaN : (a - b) / 3),
    alwaysOne: () => 1,
    alwaysMinusOne: () => -1,
    alwaysZero: () => 0,
};

const FNV_OFFSET = 2166136261;
const fnv = (h, x) => Math.imul(h ^ x, 16777619) >>> 0;

function sortFixtures() {
    const sizes = [0, 1, 2, 3, 5, 7, 8, 9, 16, 31, 32, 33, 63, 64, 65, 100, 128, 129, 255, 256, 257, 600, 1000, 1500, 2048, 3001];
    const cases = [];
    let seed = 1;
    for (const mode of Object.keys(SORT_MODES)) {
        for (const kind of Object.keys(SORT_KINDS)) {
            for (const n of sizes) {
                seed++;
                const values = SORT_MODES[mode](rng(seed), n);
                const rc = rng(seed ^ 0x5bd1e995);
                const ids = values.map((_, i) => i);
                let count = 0;
                let callHash = FNV_OFFSET;
                ids.sort((a, b) => {
                    count++;
                    callHash = fnv(fnv(callHash, a), b);
                    return SORT_KINDS[kind](values[a], values[b], rc);
                });
                const resultHash = ids.reduce(fnv, FNV_OFFSET);
                cases.push([seed, mode, kind, n, count, callHash, resultHash, n <= 33 ? ids : null]);
            }
        }
    }

    const r = rng(5);
    const strings = [];
    for (let i = 0; i < 300; i++) {
        const arr = Array.from({ length: r.int(40) }, () => randomString(r, 4, ['a', 'b', 'B', 'é', '～', '\u{1f600}', '\u{10400}', ' ', '1', '10', '9']));
        strings.push([arr, [...arr].sort()]);
    }

    dump('sort.json', { cases, strings });
}

// JS regex classes in non-unicode mode, for the `regex` crate fragments in
// src/js_regex.rs. Code units of the BMP only: a non-`u` JS regex sees an
// astral char as two surrogates, which a Rust `&str` regex cannot.
function regexes() {
    const bmp = (re) => {
        const out = [];
        for (let unit = 0; unit <= 0xffff; unit++) {
            if (unit >= 0xd800 && unit <= 0xdfff) continue;
            if (re.test(String.fromCharCode(unit))) out.push(unit);
        }
        return out;
    };
    for (let cp = 0x10000; cp <= MAX_CP; cp++) {
        if (/\s|\w|\d/.test(charOf(cp))) throw new Error(`astral class member ${cp}`);
    }
    const ignoreCase = {};
    for (const letter of 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ') {
        ignoreCase[letter] = bmp(new RegExp(`^${letter}$`, 'i'));
    }
    const r = rng(6);
    const boundary = [];
    for (let i = 0; i < 2000; i++) {
        const s = randomString(r, 8, ['a', 'Z', '0', '_', ' ', '-', '.', '\u00e9', '\u00df', '\u0130', '\u212a', '\u017f', '\u0661', '\u{1f600}', '\u{1d400}']);
        const at = [];
        for (let p = 0; p <= s.length; p++) {
            const re = /\b/y;
            re.lastIndex = p;
            if (re.test(s)) at.push(p);
        }
        boundary.push([s, at]);
    }
    dump('regex.json', { s: bmp(/^\s$/), w: bmp(/^\w$/), d: bmp(/^\d$/), notDot: bmp({ test: (c) => !/^.$/.test(c) }), ignoreCase: [ignoreCase], boundary });
}

// Array.prototype.slice on arrays of 0..8 elements: random indexes around
// the bounds, an omitted end (null), and the i32 extremes.
