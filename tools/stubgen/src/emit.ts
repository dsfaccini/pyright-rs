// Emits one Rust module per TypeScript file.
//
// 'stubs' mode writes every item of the file: types, consts, and every function and method with a
// `todo!()` body. 'deps' mode writes only the types that other emitted code names, so the stubs
// compile before their dependencies are ported.

import ts from 'typescript';
import { Gen, FamilyMember, Site, memberName, isNullish } from './gen.ts';
import { IR, Uses, isCopy, opt, render, renderField } from './ir.ts';
import { crateModuleOf, fieldName, modulePathOf, pascal, rustIdent, screaming, snake } from './names.ts';
import { hasModifier, isExported, lineOf, propName } from './program.ts';
import { Factory, Family } from './table.ts';
import { skipParens } from './writes.ts';

export type EmitMode = 'stubs' | 'deps';

export const trace = { on: false };

interface FnShape {
    name: string;
    vis: string;
    receiver: string | undefined;
    decl: ts.SignatureDeclaration;
    site: string;
    // Generic parameters declared by an enclosing impl or trait; not repeated on the method.
    outerGenerics: Set<string>;
    body: boolean;
    // A body other than `todo!()` (trait accessors).
    bodyText?: string;
    doc?: string[];
    // Overrides the declaration's own parameters and return type.
    params?: readonly ts.ParameterDeclaration[];
    retNode?: ts.TypeNode;
    // Values for type parameters of an ancestor whose method this one implements.
    subst?: Map<string, IR>;
    // The marker line, when the signature comes from another declaration.
    markerNode?: ts.Node;
    // In a `&mut self` class, callback parameters get the receiver as their first argument
    // (`&mut dyn FnMut(&mut Binder)`): a closure cannot capture `self` while the method holds it.
    ownerArg?: string;
    // Every parameter is stored (a closure factory's parameters live in its struct).
    storesParams?: boolean;
    // Leave out the `/// Nested in the TS body:` line (a factory's nested functions are methods).
    noNestedDoc?: boolean;
}

export class FileEmitter {
    readonly uses = new Uses();
    readonly out: string[] = [];
    readonly notes: string[] = [];
    readonly modPath: string;
    private readonly emittedStructs = new Set<string>();
    private readonly implNames = new Map<string, Set<string>>();

    constructor(
        readonly gen: Gen,
        readonly file: string,
        readonly sf: ts.SourceFile,
        readonly mode: EmitMode,
        readonly only: Set<string> | undefined
    ) {
        this.modPath = crateModuleOf(file);
    }

    private wants(name: string): boolean {
        return this.mode === 'stubs' || (this.only?.has(name) ?? false);
    }

    private marker(node: ts.Node): string {
        return `// ${this.file}:${lineOf(node)}`;
    }

    private site(key: string): Site {
        return { file: this.file, key, count: 0 };
    }

    run(): string {
        for (const st of this.sf.statements) {
            this.statement(st);
        }
        this.emitAnonStructs();
        return this.finish();
    }

    private finish(): string {
        const header = [
            `//! Stubs for \`packages/pyright-internal/src/${this.file}\`, generated by tools/stubgen.`,
            this.mode === 'deps'
                ? '//! Dependency placeholder: only the types other stubs name. Never copy it into crates/.'
                : '//! Every body is `todo!()`. Port each one from the TypeScript at its marker.',
            '#![allow(unused_variables, unused_imports, dead_code, non_camel_case_types, clippy::all)]',
            '',
        ];
        const uses = [...this.uses.set]
            .filter((u) => !u.startsWith(this.modPath + '::') || u.slice(this.modPath.length + 2).includes('::'))
            .sort();
        return [...header, ...groupUses(uses), '', ...this.out].join('\n') + '\n';
    }

    // ---- statements -----------------------------------------------------------------------

    private statement(st: ts.Statement) {
        if (trace.on) {
            console.error(`${this.mode} ${this.file}:${lineOf(st)}`);
        }
        if (ts.isInterfaceDeclaration(st)) {
            this.interfaceDecl(st);
        } else if (ts.isClassDeclaration(st)) {
            this.classDecl(st);
        } else if (ts.isEnumDeclaration(st)) {
            if (this.wants(st.name.text)) {
                this.enumDecl(st);
            }
        } else if (ts.isTypeAliasDeclaration(st)) {
            if (this.wants(st.name.text)) {
                this.aliasDecl(st);
            }
        } else if (ts.isFunctionDeclaration(st)) {
            if (this.mode === 'stubs' || this.isWantedFactory(st)) {
                this.functionDecl(st);
            }
        } else if (ts.isModuleDeclaration(st)) {
            if (this.mode === 'stubs') {
                this.namespaceDecl(st);
            }
        } else if (ts.isVariableStatement(st)) {
            if (this.mode === 'stubs') {
                this.variableStatement(st, undefined);
            }
        }
    }

    private isWantedFactory(st: ts.FunctionDeclaration): boolean {
        const name = st.name?.text;
        if (!name || !st.body) {
            return false;
        }
        const key = `${this.file}:${name}`;
        return [...this.gen.factoryByFunc].some(([k, f]) => (k === key || k.startsWith(`${key}.`)) && this.wants(f.name));
    }

    // ---- interfaces -----------------------------------------------------------------------

    private interfaceDecl(decl: ts.InterfaceDeclaration) {
        const name = decl.name.text;
        const key = `${this.file}:${name}`;
        const fam = this.gen.familyByRootKey.get(key);
        if (fam && fam.base === name) {
            if (this.wants(name) || this.mode === 'deps') {
                this.familyRoot(fam, decl);
            }
            return;
        }
        if (fam) {
            return;
        }
        const member = this.gen.familyMembers.get(key);
        if (member) {
            if (this.mode === 'stubs' || this.familyWanted(member.fam)) {
                this.familyMember(member);
            }
            return;
        }
        if (!this.wants(name) || this.emittedStructs.has(name)) {
            return;
        }
        if (this.gen.factoryByIface.has(key)) {
            const f = this.gen.factoryByIface.get(key);
            this.out.push(`${this.marker(decl)}: \`${name}\` is the struct \`${f?.name}\` that \`${f?.func}\` builds in ${f?.file}.`, '');
            return;
        }
        const merged = this.gen.table.merge.get(key);
        if (merged) {
            const ir = this.gen.mapKey(key, [], undefined, this.site(name));
            this.out.push(this.marker(decl), `pub type ${name} = ${render(ir, 'field', this.uses)};`, '');
            return;
        }
        if (this.gen.traitClasses.has(key)) {
            this.interfaceTrait(decl);
            return;
        }
        this.emittedStructs.add(name);
        this.struct(decl, name, this.gen.modeOf(key));
    }

    private familyWanted(fam: Family): boolean {
        return this.mode === 'stubs' || [...(this.only ?? [])].some((n) => {
            const k = `${this.file}:${n}`;
            return this.gen.familyMembers.get(k)?.fam === fam || this.gen.familyByRootKey.get(k) === fam || this.gen.familyAliases.get(k) === fam;
        });
    }

    private typeParams(decl: { typeParameters?: ts.NodeArray<ts.TypeParameterDeclaration> }): string[] {
        return (decl.typeParameters ?? []).map((tp) => tp.name.text);
    }

    // A struct from interface or class fields.
    private struct(decl: ts.InterfaceDeclaration | ts.ClassDeclaration, name: string, mode: 'handle' | 'value' | 'owned' | 'opaque', extraProps: ts.Node[] = []) {
        if (mode === 'opaque') {
            this.out.push(
                this.marker(decl),
                `// Ported by hand: the TypeScript ${ts.isClassDeclaration(decl) ? 'class' : 'interface'} does not map field by field.`,
                '#[derive(Clone, PartialEq, Eq, Hash, Debug)]',
                `pub struct ${name} {`,
                '    _opaque: (),',
                '}',
                ''
            );
            return;
        }
        const sp = this.gen.structParams(decl);
        const tps = sp.kept;
        const generics = tps.length ? `<${tps.join(', ')}>` : '';
        const fields: string[] = [];
        void extraProps;
        const props = this.gen.collectProps(decl, sp.erased);
        const used = new Set<string>();
        for (const p of props) {
            const f = this.field(p.node, name, mode === 'handle', false, p.subst);
            if (f) {
                fields.push(f);
                for (const tp of tps) {
                    if (new RegExp(`\\b${tp}\\b`).test(f)) {
                        used.add(tp);
                    }
                }
            }
        }
        for (const m of decl.members) {
            if (ts.isMethodSignature(m) && ts.isInterfaceDeclaration(decl)) {
                const f = this.methodSigField(m, name);
                if (f) {
                    fields.push(f);
                }
            }
        }
        // Interfaces merged into this one ([merge]) add the fields this one lacks, as Options.
        const key = `${this.file}:${name}`;
        const have = new Set(props.map((p) => memberName(p.node)));
        for (const [src, target] of this.gen.table.merge) {
            const targetKey = target.includes(':') ? target : `${this.gen.fileOfKey(src)}:${target}`;
            const srcDecl = targetKey === key ? this.gen.decls.get(src)?.find(ts.isInterfaceDeclaration) : undefined;
            if (!srcDecl) {
                continue;
            }
            for (const p of this.gen.collectProps(srcDecl)) {
                const n = memberName(p.node);
                if (n === undefined || have.has(n)) {
                    continue;
                }
                have.add(n);
                const f = this.field(p.node, name, mode === 'handle', false, p.subst);
                if (f) {
                    fields.push(`    // From ${this.gen.nameOfKey(src)}.`, f.includes(': Option<') ? f : f.replace(/: (.*),$/, ': Option<$1>,'));
                }
            }
        }
        const unused = tps.filter((t) => !used.has(t));
        if (unused.length) {
            this.uses.add(['std::marker::PhantomData']);
            fields.push(`    pub _phantom: PhantomData<(${unused.join(', ')}${unused.length === 1 ? ',' : ''})>,`);
        }
        // A value is copied where the TypeScript spreads it or reads it out of a container.
        const derive = mode === 'value' ? ['#[derive(Clone)]'] : [];
        this.out.push(this.marker(decl), ...derive, `pub struct ${name}${generics} {`, ...fields, '}', '');
    }

    private fieldInterior(p: ts.Node, t: IR, handle: boolean, forced: boolean): boolean {
        if (forced) {
            return true;
        }
        const m = this.gen.table.mutable.get(`${this.file}:${this.currentStruct}.${memberName(p)}`);
        if (m !== undefined) {
            return m;
        }
        if (!handle) {
            return false;
        }
        const w = this.gen.writes;
        if (w.written.has(p) || w.mutated.has(p)) {
            return true;
        }
        return w.writtenThrough.has(p) && !isCopy(t) && (t.k === 'named' || t.k === 'opt');
    }

    private currentStruct = '';
    // Static fields of the class being emitted.
    private classStatics: string[] = [];

    private field(p: ts.Node, owner: string, handle: boolean, forceInterior = false, subst?: Map<string, IR>): string | undefined {
        const name = memberName(p);
        if (name === undefined) {
            return undefined;
        }
        if (!(ts.isPropertySignature(p) || ts.isPropertyDeclaration(p) || ts.isParameter(p))) {
            return undefined;
        }
        this.currentStruct = owner;
        let t = this.gen.mapDecl(p.type, p, this.site(`${owner}.${name}`), subst);
        if (p.questionToken) {
            t = opt(t);
        }
        const interior = this.fieldInterior(p, t, handle, forceInterior);
        const vis = isPrivate(p) ? 'pub(crate)' : 'pub';
        return `    ${vis} ${fieldName(name)}: ${renderField(t, this.uses, interior)},`;
    }

    private methodSigField(m: ts.MethodSignature, owner: string): string | undefined {
        const name = propName(m.name);
        if (name === undefined) {
            return undefined;
        }
        const site = this.site(`${owner}.${name}`);
        const params = m.parameters.map((p) => {
            const t = this.gen.mapDecl(p.type, p, site);
            return p.questionToken ? opt(t) : t;
        });
        const ret = this.gen.mapDecl(m.type, m, site);
        let t: IR = { k: 'fn', params, ret };
        if (m.questionToken) {
            t = opt(t);
        }
        return `    pub ${fieldName(name)}: ${renderField(t, this.uses, false)},`;
    }

    // ---- families -------------------------------------------------------------------------

    private familyRoot(fam: Family, base: ts.InterfaceDeclaration) {
        const members = [...this.gen.familyMembers.values()].filter((m) => m.fam === fam);
        const fields: string[] = [];
        for (const { node: p } of this.gen.collectProps(base)) {
            const name = memberName(p);
            if (name === undefined || this.isSlot(p)) {
                continue;
            }
            const f = this.field(p, fam.name, true, fam.allFieldsMutable && name !== fam.kind && name !== 'id');
            if (f) {
                fields.push(f);
            }
        }
        fields.push(`    pub ${fam.detailsField}: ${fam.name}Details,`);
        this.out.push(this.marker(base), `pub struct ${fam.name} {`, ...fields, '}', '');

        const variants: string[] = [];
        if (fam.rootVariant) {
            variants.push(`    ${fam.rootVariant},`);
        }
        const seen = new Set<string>();
        for (const m of members) {
            if (m.sharesVariantOf || seen.has(m.variant)) {
                continue;
            }
            seen.add(m.variant);
            variants.push(fam.emptyVariants === 'unit' && !this.memberHasFields(m) ? `    ${m.variant},` : `    ${m.variant}(${m.name}Details),`);
        }
        this.out.push(`// ${fam.file}: one variant per ${fam.kind ? `\`${fam.kind}\` value` : 'interface'}.`, `pub enum ${fam.name}Details {`, ...variants, '}', '');
    }

    // A base property typed `object` is a per-kind slot: each member redeclares it.
    private isSlot(p: ts.Node): boolean {
        if (!(ts.isPropertySignature(p) && p.type)) {
            return false;
        }
        const t = p.type;
        const parts = ts.isUnionTypeNode(t) ? t.types.filter((x) => !isNullish(x)) : [t];
        return parts.length === 1 && parts[0].kind === ts.SyntaxKind.ObjectKeyword;
    }

    // The fields a member's details struct holds, and whether there are none.
    private memberHasFields(m: FamilyMember): boolean {
        const fam = m.fam;
        const base = this.gen.decls.get(`${fam.file}:${fam.base}`)?.find(ts.isInterfaceDeclaration);
        const baseSlots = new Set<string>();
        const baseNames = new Set<string>();
        for (const { node: p } of base ? this.gen.collectProps(base) : []) {
            const n = memberName(p);
            if (n !== undefined) {
                (this.isSlot(p) ? baseSlots : baseNames).add(n);
            }
        }
        if (m.parent) {
            return true;
        }
        const props = this.gen.collectProps(m.decl).map((p) => p.node);
        return props.some((p) => {
            const n = memberName(p);
            return n !== undefined && !(baseNames.has(n) && !baseSlots.has(n)) && !this.isSlot(p);
        });
    }

    private familyMember(m: FamilyMember) {
        const fam = m.fam;
        const decl = m.decl;
        if (fam.emptyVariants === 'unit' && !m.sharesVariantOf && !this.memberHasFields(m)) {
            // A unit variant: no details struct, and no typed handle to reach one.
            this.out.push(`${this.marker(decl)}: \`${m.name}\` has no fields of its own: \`${fam.name}Details::${m.variant}\`.`, '');
            return;
        }
        const baseKey = `${fam.file}:${fam.base}`;
        const base = this.gen.decls.get(baseKey)?.find(ts.isInterfaceDeclaration);
        const baseSlots = new Set<string>();
        const baseNames = new Set<string>();
        for (const { node: p } of base ? this.gen.collectProps(base) : []) {
            const n = memberName(p);
            if (n !== undefined) {
                (this.isSlot(p) ? baseSlots : baseNames).add(n);
            }
        }
        if (!m.sharesVariantOf) {
            const fields: string[] = [];
            if (m.parent) {
                fields.push(`    pub base: ${m.parent}Details,`);
            }
            // Fields of this interface that are not on the base. A redeclared base field only
            // narrows its type; it stays on the root. Members of a family without a kind field
            // embed their parent's details instead of repeating its fields.
            const props = m.parent ? ownProps(decl) : this.gen.collectProps(decl).map((p) => p.node);
            for (const p of props) {
                const n = memberName(p);
                if (n === undefined || (baseNames.has(n) && !baseSlots.has(n))) {
                    continue;
                }
                if (this.isSlot(p)) {
                    // The base's own `object` slot: this member does not redeclare it.
                    continue;
                }
                if (fam.flatten && n === fam.flatten && ts.isPropertySignature(p) && p.type && ts.isTypeLiteralNode(p.type)) {
                    for (const inner of p.type.members) {
                        const f = this.field(inner, `${m.name}.${n}`, true, fam.allFieldsMutable);
                        if (f) {
                            fields.push(f);
                        }
                    }
                    continue;
                }
                const f = this.field(p, m.name, true, fam.allFieldsMutable);
                if (f) {
                    fields.push(f);
                }
            }
            this.out.push(this.marker(decl), `pub struct ${m.name}Details {`, ...fields, '}', '');
        }
        if (fam.typedHandles) {
            this.typedHandle(m);
        }
    }

    // `FunctionNode(P<ParseNode>)` with `cast`, `d` and `Deref`, per docs/porting.md "parse nodes".
    private typedHandle(m: FamilyMember) {
        const fam = m.fam;
        this.uses.add(['jsrt::P', 'std::ops::Deref']);
        const detailsOwner = m.sharesVariantOf ?? m.name;
        // Variants whose details contain this member's details.
        const arms: string[] = [];
        const all = [...this.gen.familyMembers.values()].filter((x) => x.fam === fam && !x.sharesVariantOf);
        for (const x of all) {
            const path: string[] = [];
            let cur: string | undefined = x.name;
            while (cur && cur !== detailsOwner) {
                path.push('base');
                cur = all.find((y) => y.name === cur)?.parent;
            }
            if (cur === detailsOwner) {
                arms.push(`            ${fam.name}Details::${x.variant}(d) => ${path.length ? `&d${path.map((p) => `.${p}`).join('')}` : 'd'},`);
            }
        }
        const castArms = arms.map((a) => a.replace(/\(d\) => .*$/, '(_)')).map((a) => a.trim());
        const lines = [
            this.marker(m.decl),
            '#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]',
            `pub struct ${m.name}(pub P<${fam.name}>);`,
            '',
            `impl ${m.name} {`,
        ];
        if (!m.sharesVariantOf) {
            lines.push(
                `    pub fn cast(node: P<${fam.name}>) -> Option<Self> {`,
                `        match node.${fam.detailsField} {`,
                `            ${castArms.join(' | ')} => Some(Self(node)),`,
                '            _ => None,',
                '        }',
                '    }',
                ''
            );
        }
        lines.push(
            `    pub fn ${fam.detailsField}(self) -> &'static ${detailsOwner}Details {`,
            `        match &self.0.get().${fam.detailsField} {`,
            ...arms,
            `            _ => unreachable!("${m.name} holds another variant"),`,
            '        }',
            '    }',
            '}',
            '',
            `impl Deref for ${m.name} {`,
            `    type Target = ${fam.name};`,
            '',
            `    fn deref(&self) -> &${fam.name} {`,
            '        self.0.get()',
            '    }',
            '}',
            ''
        );
        this.out.push(...lines);
    }

    // ---- traits ---------------------------------------------------------------------------

    private interfaceTrait(decl: ts.InterfaceDeclaration) {
        const name = decl.name.text;
        this.currentImpl = name;
        const key = `${this.file}:${name}`;
        const receiver = this.gen.table.traits.get(key)?.receiver ?? '&self';
        const tps = this.typeParams(decl);
        const supers = this.superTraits(decl);
        const head = `pub trait ${name}${tps.length ? `<${tps.join(', ')}>` : ''}${supers.length ? `: ${supers.join(' + ')}` : ''} {`;
        const items: string[] = [];
        for (const m of decl.members) {
            const mname = memberName(m);
            if (mname === undefined) {
                continue;
            }
            if (ts.isMethodSignature(m)) {
                items.push(...this.fnStub({ name: mname, vis: '', receiver, decl: m, site: `${name}.${mname}`, outerGenerics: new Set(tps), body: false }, '    '));
            } else if (ts.isPropertySignature(m)) {
                const t = this.gen.mapDecl(m.type, m, this.site(`${name}.${mname}`));
                const tt = m.questionToken ? opt(t) : t;
                if (tt.k === 'fn') {
                    const params = tt.params.map((p, i) => `a${i}: ${render(p, 'param', this.uses)}`);
                    const ret = tt.ret.k === 'unit' ? '' : ` -> ${render(tt.ret, 'ret', this.uses)}`;
                    items.push(`    ${this.marker(m)}`, `    fn ${fieldName(mname)}(${[receiver, ...params].join(', ')})${ret};`, '');
                } else {
                    items.push(`    ${this.marker(m)}`, `    fn ${fieldName(mname)}(&self) -> ${accessorType(tt, this.uses)};`, '');
                }
            }
        }
        this.out.push(this.marker(decl), head, ...trimBlank(items), '}', '');
    }

    private superTraits(decl: ts.InterfaceDeclaration | ts.ClassDeclaration): string[] {
        const out: string[] = [];
        for (const h of decl.heritageClauses ?? []) {
            if (h.token !== ts.SyntaxKind.ExtendsKeyword) {
                continue;
            }
            for (const t of h.types) {
                const key = this.gen.keyOfSymbol(this.gen.checker.getSymbolAtLocation(t.expression));
                if (key && this.gen.traitClasses.has(key)) {
                    const args = (t.typeArguments ?? []).map((a) => render(this.gen.mapNode(a, this.site('_'), new Map()), 'elem', this.uses));
                    const n = this.gen.nameOfKey(key);
                    this.uses.add([`${crateModuleOf(this.gen.fileOfKey(key))}::${n}`]);
                    out.push(n + (args.length ? `<${args.join(', ')}>` : ''));
                }
            }
        }
        return out;
    }

    // ---- classes --------------------------------------------------------------------------

    private classDecl(decl: ts.ClassDeclaration) {
        const name = decl.name?.text;
        if (!name || !this.wants(name)) {
            return;
        }
        const key = `${this.file}:${name}`;
        if (this.gen.traitClasses.has(key)) {
            this.classTrait(decl, name);
            return;
        }
        const mode = this.gen.modeOf(key);
        const traitAncestors = this.gen.traitAncestors(key);
        const ext = decl.heritageClauses?.find((h) => h.token === ts.SyntaxKind.ExtendsKeyword)?.types[0];
        if (ext && traitAncestors.length === 0) {
            this.out.push(`// ${name} extends ${ext.getText()}: the base fields are repeated below.`);
        }
        this.currentImpl = name;
        this.struct(decl, name, mode);
        if (this.mode === 'deps') {
            return;
        }
        const recv = mode === 'owned' ? '&mut self' : '&self';
        const tps = this.gen.structParams(decl).kept;
        const generics = tps.length ? `<${tps.join(', ')}>` : '';
        const selfType = name + generics;

        // Which trait impl each method belongs to, and the trait's own declaration of it: a trait
        // impl must use the trait's signature, with the ancestor's type arguments filled in.
        const substs = this.gen.ancestorSubsts(decl);
        const traitOf = new Map<string, { trait: string; member: ts.Node }>();
        const traitImpls = new Map<string, string[]>();
        const traitHeads = new Map<string, string>();
        const ifaceTraits = this.implementedTraits(decl);
        const classMembers = new Set(decl.members.map((m) => memberName(m)).filter((n): n is string => n !== undefined));
        for (const t of [...traitAncestors, ...ifaceTraits]) {
            const tdecl = this.gen.decls.get(t)?.find((d) => ts.isClassDeclaration(d) || ts.isInterfaceDeclaration(d));
            if (!tdecl || !(ts.isClassDeclaration(tdecl) || ts.isInterfaceDeclaration(tdecl))) {
                continue;
            }
            const sub = substs.get(t) ?? new Map<string, IR>();
            const lines: string[] = [];
            traitImpls.set(t, lines);
            traitHeads.set(t, this.traitImplHead(decl, t, selfType));
            for (const m of tdecl.members) {
                const n = memberName(m);
                if (n === undefined || traitOf.has(n)) {
                    continue;
                }
                const isFnProp = ts.isPropertySignature(m) && m.type !== undefined && ts.isFunctionTypeNode(m.type);
                if (ts.isMethodDeclaration(m) || ts.isMethodSignature(m) || isFnProp) {
                    traitOf.set(n, { trait: t, member: m });
                    if (ts.isInterfaceDeclaration(tdecl) && !classMembers.has(n)) {
                        // The class gets this method from elsewhere (a base class, a field).
                        lines.push(...this.traitMethodStub(m, n, '&self', sub, `${name}.${n}`));
                    }
                } else if (ts.isPropertySignature(m)) {
                    // A data member of an interface trait: an accessor.
                    const t2 = this.gen.mapDecl(m.type, m, this.site(`${tdecl.name?.text}.${n}`), sub);
                    lines.push(`    ${this.marker(m)}`, `    fn ${fieldName(n)}(&self) -> ${accessorType(m.questionToken ? opt(t2) : t2, this.uses)} {`, '        todo!()', '    }', '');
                }
            }
            if (ts.isClassDeclaration(tdecl)) {
                // The trait class's fields live in this struct; the trait reads them through accessors.
                for (const p of ownFieldNodes(tdecl)) {
                    const n = memberName(p);
                    if (n === undefined) {
                        continue;
                    }
                    const wrap = (x: IR) => (isOptionalMember(p) ? opt(x) : x);
                    const t2 = wrap(this.gen.mapDecl(fieldTypeNode(p), p, this.site(`${tdecl.name?.text}.${n}`), sub));
                    // By value only when the trait itself returns it by value (a generic `T` is `&T`).
                    const copy = isCopy(wrap(this.gen.mapDecl(fieldTypeNode(p), p, this.site(`${tdecl.name?.text}.${n}`))));
                    const f = fieldName(n);
                    const ty = render(t2, 'field', this.uses);
                    const body = mode === 'owned' ? `${copy ? '' : '&'}self.${f}` : 'todo!()';
                    lines.push(`    fn ${f}(&self) -> ${copy ? ty : `&${ty}`} {`, `        ${body}`, '    }', '');
                }
            }
        }
        const inherent: string[] = [];
        for (const m of decl.members) {
            const n = memberName(m);
            const tm = n !== undefined && !ts.isConstructorDeclaration(m) && !ts.isPropertyDeclaration(m) ? traitOf.get(n) : undefined;
            if (tm && n !== undefined && (ts.isMethodDeclaration(m) || ts.isGetAccessorDeclaration(m))) {
                const traitRecv = this.gen.table.traits.get(tm.trait)?.receiver ?? (this.gen.decls.get(tm.trait)?.some(ts.isClassDeclaration) ? '&mut self' : '&self');
                traitImpls.get(tm.trait)?.push(...this.traitMethodStub(tm.member, n, traitRecv, substs.get(tm.trait) ?? new Map(), `${name}.${n}`, m));
                continue;
            }
            const lines = this.classMember(m, name, recv, new Set(tps), new Map());
            if (lines) {
                inherent.push(...lines);
            }
        }
        for (const [t, lines] of traitImpls) {
            this.out.push(`${traitHeads.get(t)} {`, ...trimBlank(lines), '}', '');
        }
        if (inherent.length) {
            this.out.push(`impl${generics} ${selfType} {`, ...trimBlank(inherent), '}', '');
        }
        this.scopedVariables(name, this.classStatics);
        this.classStatics = [];
        this.currentImpl = '';
    }

    // A trait method in an impl block, with the trait's signature and the implementing method's marker.
    private traitMethodStub(member: ts.Node, n: string, receiver: string, subst: Map<string, IR>, site: string, impl?: ts.Node): string[] {
        let params: readonly ts.ParameterDeclaration[] | undefined;
        let retNode: ts.TypeNode | undefined;
        let decl: ts.SignatureDeclaration | undefined;
        if (ts.isMethodDeclaration(member) || ts.isMethodSignature(member)) {
            decl = member;
        } else if (ts.isPropertySignature(member) && member.type && ts.isFunctionTypeNode(member.type)) {
            decl = member.type;
            params = member.type.parameters;
            retNode = member.type.type;
        }
        if (!decl) {
            return [];
        }
        // An unannotated trait method infers its return type from its own body.
        if (!retNode && !decl.type && impl && (ts.isMethodDeclaration(impl) || ts.isGetAccessorDeclaration(impl)) && impl.type) {
            retNode = undefined;
        }
        const lines = this.fnStub({ name: n, vis: '', receiver, decl, site, outerGenerics: new Set(), body: true, params, retNode, subst, markerNode: impl ?? member }, '    ');
        return lines;
    }

    private implementedTraits(decl: ts.ClassDeclaration): string[] {
        const out: string[] = [];
        const visit = (key: string) => {
            if (out.includes(key)) {
                return;
            }
            const d = this.gen.decls.get(key)?.find(ts.isInterfaceDeclaration);
            if (!d) {
                return;
            }
            out.push(key);
            for (const h of d.heritageClauses ?? []) {
                for (const t of h.types) {
                    const k = this.gen.keyOfSymbol(this.gen.checker.getSymbolAtLocation(t.expression));
                    if (k && this.gen.traitClasses.has(k)) {
                        visit(k);
                    }
                }
            }
        };
        for (const h of decl.heritageClauses ?? []) {
            if (h.token !== ts.SyntaxKind.ImplementsKeyword) {
                continue;
            }
            for (const t of h.types) {
                const k = this.gen.keyOfSymbol(this.gen.checker.getSymbolAtLocation(t.expression));
                if (k && this.gen.traitClasses.has(k)) {
                    visit(k);
                }
            }
        }
        return out;
    }

    private traitImplHead(decl: ts.ClassDeclaration, traitKey: string, selfType: string): string {
        const n = this.gen.nameOfKey(traitKey);
        this.uses.add([`${crateModuleOf(this.gen.fileOfKey(traitKey))}::${n}`]);
        // Type arguments the class passes to the trait class, found along the extends chain.
        let args: string[] = [];
        let cur: ts.ClassDeclaration | undefined = decl;
        for (let i = 0; i < 10 && cur; i++) {
            const ext: ts.ExpressionWithTypeArguments | undefined = cur.heritageClauses?.find((h) => h.token === ts.SyntaxKind.ExtendsKeyword)?.types[0];
            if (!ext) {
                break;
            }
            const k = this.gen.keyOfSymbol(this.gen.checker.getSymbolAtLocation(ext.expression));
            if (k === traitKey) {
                args = (ext.typeArguments ?? []).map((a) => render(this.gen.mapNode(a, this.site('_'), new Map()), 'elem', this.uses));
                break;
            }
            // Walk into the next base's own extends clause (ParseTreeWalker extends ParseTreeVisitor<boolean>).
            const next = k ? this.gen.decls.get(k)?.find(ts.isClassDeclaration) : undefined;
            cur = next;
        }
        const tps = this.typeParams(decl);
        return `impl${tps.length ? `<${tps.join(', ')}>` : ''} ${n}${args.length ? `<${args.join(', ')}>` : ''} for ${selfType}`;
    }

    private classTrait(decl: ts.ClassDeclaration, name: string) {
        this.currentImpl = name;
        const key = `${this.file}:${name}`;
        const receiver = this.gen.table.traits.get(key)?.receiver ?? '&mut self';
        const tps = this.typeParams(decl);
        const supers = this.superTraits(decl);
        const head = `pub trait ${name}${tps.length ? `<${tps.join(', ')}>` : ''}${supers.length ? `: ${supers.join(' + ')}` : ''} {`;
        const items: string[] = [];
        for (const p of ownFieldNodes(decl)) {
            const n = memberName(p);
            if (n === undefined) {
                continue;
            }
            const t = this.gen.mapDecl(fieldTypeNode(p), p, this.site(`${name}.${n}`));
            items.push(`    ${this.marker(p)}`, `    fn ${fieldName(n)}(&self) -> ${accessorType(isOptionalMember(p) ? opt(t) : t, this.uses)};`, '');
        }
        if (this.mode === 'stubs') {
            for (const m of decl.members) {
                if (ts.isConstructorDeclaration(m) || ts.isPropertyDeclaration(m)) {
                    continue;
                }
                const lines = this.classMember(m, name, receiver, new Set(tps), new Map(), true);
                if (lines) {
                    items.push(...lines.map((l) => l.replace(/^    pub(\(crate\))? fn /, '    fn ')));
                }
            }
        }
        this.out.push(this.marker(decl), head, ...trimBlank(items), '}', '');
    }

    private classMember(
        m: ts.ClassElement,
        cls: string,
        recv: string,
        outer: Set<string>,
        traitOf: Map<string, string>,
        inTrait = false
    ): string[] | undefined {
        const isStatic = hasModifier(m, ts.SyntaxKind.StaticKeyword);
        const vis = (n: ts.Node) => (inTrait ? '' : isPrivate(n) ? 'pub(crate) ' : 'pub ');
        if (ts.isConstructorDeclaration(m)) {
            if (!m.body) {
                return undefined;
            }
            const mode = this.gen.modeOf(`${this.file}:${cls}`);
            const generics = outer.size ? `<${[...outer].join(', ')}>` : '';
            const ret = mode === 'handle' ? `P<${cls}${generics}>` : 'Self';
            if (mode === 'handle') {
                this.uses.add(['jsrt::P']);
            }
            return this.fnStub({ name: 'new', vis: 'pub ', receiver: undefined, decl: m, site: `${cls}.constructor`, outerGenerics: outer, body: true }, '    ', ret);
        }
        if (ts.isMethodDeclaration(m)) {
            const n = memberName(m);
            if (n === undefined || (!m.body && !hasModifier(m, ts.SyntaxKind.AbstractKeyword))) {
                return undefined;
            }
            void traitOf;
            const abstract = !m.body;
            const ownerArg = recv === '&mut self' && !isStatic && !inTrait ? cls + (outer.size ? `<${[...outer].join(', ')}>` : '') : undefined;
            return this.fnStub(
                { name: n, vis: vis(m), receiver: isStatic ? undefined : recv, decl: m, site: `${cls}.${n}`, outerGenerics: outer, body: !(abstract && inTrait), ownerArg },
                '    '
            );
        }
        if (ts.isGetAccessorDeclaration(m)) {
            const n = memberName(m);
            if (n === undefined) {
                return undefined;
            }
            return this.fnStub({ name: n, vis: vis(m), receiver: isStatic ? undefined : '&self', decl: m, site: `${cls}.${n}`, outerGenerics: outer, body: true }, '    ');
        }
        if (ts.isSetAccessorDeclaration(m)) {
            const n = memberName(m);
            if (n === undefined) {
                return undefined;
            }
            return this.fnStub({ name: `set_${snake(n)}`, vis: vis(m), receiver: isStatic ? undefined : recv, decl: m, site: `${cls}.${n}`, outerGenerics: outer, body: true }, '    ');
        }
        if (ts.isPropertyDeclaration(m) && isStatic) {
            const n = memberName(m);
            if (n === undefined || this.mode !== 'stubs') {
                return undefined;
            }
            const w = this.gen.writes;
            const neverWritten = !w.written.has(m) && !w.reassigned.has(m);
            this.classStatics.push(...this.moduleVariable(m, n, cls, m.initializer, m.type, hasModifier(m, ts.SyntaxKind.ReadonlyKeyword) || neverWritten));
            return undefined;
        }
        return undefined;
    }

    // ---- functions ------------------------------------------------------------------------

    private functionDecl(fn: ts.FunctionDeclaration) {
        const name = fn.name?.text;
        if (!name || !fn.body) {
            return;
        }
        const factory = this.gen.factoryByFunc.get(`${this.file}:${name}`);
        if (factory) {
            this.factory(factory, fn, undefined);
            return;
        }
        const vis = isExported(fn) ? 'pub ' : 'pub(crate) ';
        this.out.push(...this.fnStub({ name, vis, receiver: undefined, decl: fn, site: name, outerGenerics: new Set(), body: true }, ''));
    }

    // `<marker>\n<doc>\npub fn name<T>(recv, params) -> ret {\n    todo!()\n}`
    fnStub(s: FnShape, indent: string, retOverride?: string): string[] {
        const decl = s.decl;
        const site = this.site(s.site);
        const params: string[] = s.receiver ? [s.receiver] : [];
        const defaults: string[] = [];
        const declParams = s.params ?? decl.parameters;
        declParams.forEach((p, i) => {
            if (ts.isIdentifier(p.name) && p.name.text === 'this') {
                return;
            }
            const pname = ts.isIdentifier(p.name) ? p.name.text : `arg${i}`;
            const psite: Site = { file: this.file, key: `${s.site}.${pname}`, count: 0 };
            let t = this.gen.mapDecl(p.type, p, psite, s.subst);
            if (p.dotDotDotToken) {
                t = t.k === 'vec' ? t : { k: 'vec', elem: t };
            } else if (p.questionToken) {
                t = opt(t);
            }
            if (s.ownerArg) {
                t = withOwnerArg(t, s.ownerArg);
            }
            if (p.initializer) {
                defaults.push(`${pname} = ${p.initializer.getText().replace(/\s+/g, ' ')}`);
            }
            const w = this.gen.writes;
            const mutated = w.mutated.has(p) || (w.writtenThrough.has(p) && !isCopy(t));
            // A parameter the function stores takes the form of the field that keeps it: by value,
            // `P<T>` for a factory struct, `&'static dyn T` for a trait.
            const stored = s.storesParams || storesParam(decl, p);
            params.push(`${rustIdent(snake(pname))}: ${render(t, stored ? 'field' : 'param', this.uses, mutated)}`);
        });
        let ret = retOverride ?? '';
        if (!retOverride) {
            const rt = this.returnIR(s, site);
            if (rt.k !== 'unit') {
                ret = render(rt, 'ret', this.uses);
            }
        }
        const sigText = params.join(', ') + ' ' + ret;
        const generics = this.fnGenerics(decl, s.outerGenerics, sigText);
        const doc: string[] = [...(s.doc ?? [])];
        if (defaults.length) {
            doc.push(`/// TS defaults: ${defaults.join(', ')}.`);
        }
        const nested = s.noNestedDoc ? [] : nestedFunctions(decl);
        if (nested.length) {
            doc.push(`/// Nested in the TS body: ${nested.join(', ')}.`);
        }
        const name = this.uniqueName(s.receiver !== undefined || indent !== '' ? 'impl' : 'mod', rustIdent(snake(s.name)));
        const head = `${s.vis}fn ${name}${generics}(${params.join(', ')})${ret ? ` -> ${ret}` : ''}`;
        const lines = [`${indent}${this.marker(s.markerNode ?? decl)}`, ...doc.map((d) => indent + d)];
        if (!s.body) {
            lines.push(`${indent}${head};`, '');
        } else {
            lines.push(`${indent}${head} {`, `${indent}    ${s.bodyText ?? 'todo!()'}`, `${indent}}`, '');
        }
        return lines;
    }

    private currentImpl = '';

    private uniqueName(scope: string, name: string): string {
        const key = scope === 'impl' ? `impl:${this.currentImpl}` : 'mod';
        const set = this.implNames.get(key) ?? new Set<string>();
        this.implNames.set(key, set);
        let n = name;
        for (let i = 2; set.has(n); i++) {
            n = `${name}_${i}`;
            this.notes.push(`renamed ${name} to ${n} in ${key}`);
        }
        set.add(n);
        return n;
    }

    private returnIR(s: FnShape, site: Site): IR {
        const override = this.gen.siteOverride({ ...site, key: `${s.site}.return` });
        if (override) {
            return override;
        }
        const decl = s.decl;
        const node = s.retNode ?? decl.type;
        if (node) {
            return this.gen.mapNode(node, { ...site, key: `${s.site}.return` }, s.subst ?? new Map());
        }
        if (ts.isConstructorDeclaration(decl) || ts.isSetAccessorDeclaration(decl)) {
            return { k: 'unit' };
        }
        const sig = this.gen.checker.getSignatureFromDeclaration(decl);
        if (!sig) {
            return { k: 'unit' };
        }
        this.gen.typeSubst = s.subst;
        try {
            return this.gen.mapType(sig.getReturnType(), { ...site, key: `${s.site}.return` }, 0);
        } finally {
            this.gen.typeSubst = undefined;
        }
    }

    // Rust generics for the TS type parameters that survive mapping.
    private fnGenerics(decl: ts.SignatureDeclaration, outer: Set<string>, sigText: string): string {
        const out: string[] = [];
        for (const tp of decl.typeParameters ?? []) {
            const n = tp.name.text;
            if (!outer.has(n) && new RegExp(`\\b${n}\\b`).test(sigText)) {
                out.push(n);
            }
        }
        return out.length ? `<${out.join(', ')}>` : '';
    }

    // ---- namespaces -----------------------------------------------------------------------

    private namespaceDecl(ns: ts.ModuleDeclaration) {
        if (!ts.isIdentifier(ns.name) || !ns.body || !ts.isModuleBlock(ns.body)) {
            return;
        }
        const name = ns.name.text;
        const key = `${this.file}:${name}`;
        const decls = this.gen.decls.get(key) ?? [];
        const hasType =
            this.gen.familyMembers.has(key) ||
            decls.some((d) => ts.isInterfaceDeclaration(d) || ts.isClassDeclaration(d) || ts.isEnumDeclaration(d)) ||
            decls.some((d) => ts.isTypeAliasDeclaration(d) && this.gen.aliasShape(d) !== 'inline');
        const isBase = this.gen.familyByRootKey.has(key);
        const isTrait = this.gen.traitClasses.has(key);
        let implTarget = name;
        if (isTrait) {
            implTarget = `${name}Fns`;
        }
        if (!hasType || isBase || isTrait) {
            if (!this.emittedStructs.has(implTarget)) {
                this.emittedStructs.add(implTarget);
                this.out.push(this.marker(ns), `// Namespace \`${name}\`: its functions are associated functions.`, `pub struct ${implTarget};`, '');
            }
        }
        this.currentImpl = `${implTarget}#${lineOf(ns)}`;
        const items: string[] = [];
        const vars: string[] = [];
        for (const st of ns.body.statements) {
            if (ts.isFunctionDeclaration(st) && st.name && st.body) {
                const vis = isExported(st) ? 'pub ' : 'pub(crate) ';
                items.push(...this.fnStub({ name: st.name.text, vis, receiver: undefined, decl: st, site: `${name}.${st.name.text}`, outerGenerics: new Set(), body: true }, '    '));
            } else if (ts.isVariableStatement(st)) {
                this.variableStatement(st, name, vars);
            } else {
                this.statement(st);
            }
        }
        this.currentImpl = '';
        if (items.length) {
            this.out.push(`impl ${implTarget} {`, ...trimBlank(items), '}', '');
        }
        this.scopedVariables(`${name}#${lineOf(ns)}`.replace(/#.*/, ''), vars);
    }

    // ---- variables ------------------------------------------------------------------------

    private variableStatement(st: ts.VariableStatement, ns: string | undefined, into?: string[]) {
        const isConst = (st.declarationList.flags & ts.NodeFlags.Const) !== 0;
        for (const d of st.declarationList.declarations) {
            if (!ts.isIdentifier(d.name)) {
                continue;
            }
            const name = d.name.text;
            const init = d.initializer ? skipParens(d.initializer) : undefined;
            if (init && (ts.isArrowFunction(init) || ts.isFunctionExpression(init))) {
                const vis = isExported(st) ? 'pub ' : 'pub(crate) ';
                const target = ns ?? '';
                if (ns) {
                    this.out.push(`// ${ns}.${name} is a function value; it is a module-level function here.`);
                }
                this.out.push(
                    ...this.fnStub(
                        { name: ns ? `${target}_${name}` : name, vis, receiver: undefined, decl: init, site: ns ? `${ns}.${name}` : name, outerGenerics: new Set(), body: true },
                        ''
                    )
                );
                continue;
            }
            const lines = this.moduleVariable(d, name, ns, d.initializer, d.type, isConst);
            (into ?? this.out).push(...lines);
        }
    }

    // A module variable, or a namespace or static class field when `scope` is set. Returns the lines;
    // the caller puts scoped ones in `pub mod <scope>` (`UnboundType._instance` is
    // `unbound_type::INSTANCE`).
    private moduleVariable(d: ts.VariableDeclaration | ts.PropertyDeclaration, tsName: string, scope: string | undefined, initializer: ts.Expression | undefined, typeNode: ts.TypeNode | undefined, isConst: boolean): string[] {
        const t = this.gen.mapDecl(typeNode, d, this.site(scope ? `${scope}.${tsName}` : tsName));
        const name = screaming(tsName);
        const lit = initializer ? literalOf(skipParens(initializer)) : undefined;
        const w = this.gen.writes;
        const written = w.reassigned.has(d) || w.written.has(d);
        const mutated = w.mutated.has(d) || w.writtenThrough.has(d);
        const exported = ts.isVariableDeclaration(d) ? isExported(d.parent.parent) : !isPrivate(d);
        const vis = exported ? 'pub ' : 'pub(crate) ';
        const float = (v: string) => (t.k === 'num' && t.rust === 'f64' && /^-?\d+$/.test(v) ? `${v}.0` : v);
        if (isConst && !written && lit !== undefined && (t.k === 'num' || t.k === 'str' || t.k === 'bool')) {
            const rt = t.k === 'str' ? '&str' : render(t, 'field', this.uses);
            return [this.marker(d), `${vis}const ${name}: ${rt} = ${float(lit)};`, ''];
        }
        const interior = !isConst || written || mutated;
        const ty = renderField(t, this.uses, interior);
        const init = interior && lit !== undefined && (t.k === 'num' || t.k === 'bool') ? `const { ${isCopy(t) ? 'Cell' : 'RefCell'}::new(${float(lit)}) }` : 'todo!()';
        return ['thread_local! {', `    ${this.marker(d)}`, `    ${vis}static ${name}: ${ty} = ${init};`, '}', ''];
    }

    private scopedVariables(scope: string, lines: string[]) {
        if (lines.length) {
            this.out.push(`// Variables of \`${scope}\`.`, `pub mod ${snake(scope)} {`, '    use super::*;', '', ...trimBlank(lines).map((l) => (l ? `    ${l}` : l)), '}', '');
        }
    }

    // ---- enums ----------------------------------------------------------------------------

    private enumDecl(e: ts.EnumDeclaration) {
        const name = e.name.text;
        const key = `${this.file}:${name}`;
        const values = e.members.map((m) => {
            const v = this.gen.checker.getConstantValue(m);
            return { name: propName(m.name) ?? 'Unknown', value: v, init: m.initializer?.getText() ?? '' };
        });
        if (values.some((v) => typeof v.value === 'string')) {
            this.out.push(
                this.marker(e),
                '#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]',
                `pub enum ${name} {`,
                ...values.map((v) => `    ${v.name},`),
                '}',
                '',
                `impl ${name} {`,
                '    pub fn as_str(self) -> &\'static str {',
                '        match self {',
                ...values.map((v) => `            ${name}::${v.name} => ${JSON.stringify(String(v.value))},`),
                '        }',
                '    }',
                '}',
                ''
            );
            return;
        }
        const forced = this.gen.table.flagEnums.get(key);
        const flags = forced ?? values.some((v) => /<<|\|/.test(v.init));
        if (flags) {
            this.uses.add(['jsrt::flag_ops']);
            this.out.push(
                this.marker(e),
                '#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug, Default)]',
                `pub struct ${name}(pub u32);`,
                '',
                `impl ${name} {`,
                ...values.map((v) => `    pub const ${v.name}: ${name} = ${name}(${hex(Number(v.value ?? 0))});`),
                '}',
                '',
                `flag_ops!(${name});`,
                ''
            );
            return;
        }
        const seen = new Map<number, string>();
        const variants: string[] = [];
        const aliases: string[] = [];
        for (const v of values) {
            const n = Number(v.value ?? 0);
            const prior = seen.get(n);
            if (prior !== undefined) {
                aliases.push(`    pub const ${v.name}: ${name} = ${name}::${prior};`);
                continue;
            }
            seen.set(n, v.name);
            variants.push(`    ${v.name} = ${n},`);
        }
        this.out.push(this.marker(e), '#[repr(i32)]', '#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]', `pub enum ${name} {`, ...variants, '}', '');
        if (aliases.length) {
            this.out.push('// Members that repeat an earlier value.', `impl ${name} {`, ...aliases, '}', '');
        }
    }

    // ---- type aliases ---------------------------------------------------------------------

    private aliasDecl(a: ts.TypeAliasDeclaration) {
        const name = a.name.text;
        const key = `${this.file}:${name}`;
        const fam = this.gen.familyByRootKey.get(key);
        if (fam) {
            this.out.push(`${this.marker(a)}: \`${name}\`, the union of every member, is \`P<${fam.name}>\`: struct ${fam.name} and enum ${fam.name}Details.`, '');
            return;
        }
        const tps = this.typeParams(a);
        const generics = tps.length ? `<${tps.join(', ')}>` : '';
        const shape = this.gen.aliasShape(a);
        const site = this.site(name);
        if (shape === 'family') {
            const fam = this.gen.familyAliases.get(key);
            if (fam) {
                this.uses.add(['jsrt::P', `${crateModuleOf(fam.file)}::${fam.name}`]);
                this.out.push(this.marker(a), `pub type ${name} = P<${fam.name}>;`, '');
            }
            return;
        }
        if (shape === 'struct' && ts.isTypeLiteralNode(a.type)) {
            this.emittedStructs.add(name);
            const fields = a.type.members.map((m) => this.field(m, name, false)).filter((f): f is string => f !== undefined);
            this.out.push(this.marker(a), '#[derive(Clone)]', `pub struct ${name}${generics} {`, ...fields, '}', '');
            return;
        }
        if (shape === 'enum' && ts.isUnionTypeNode(a.type)) {
            const parts = a.type.types.filter((p) => !isNullish(p));
            if (parts.every((p) => ts.isLiteralTypeNode(p) && ts.isStringLiteral(p.literal))) {
                const lits = parts.map((p) => (ts.isLiteralTypeNode(p) && ts.isStringLiteral(p.literal) ? p.literal.text : ''));
                this.out.push(
                    this.marker(a),
                    '#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]',
                    `pub enum ${name} {`,
                    ...lits.map((l) => `    ${pascal(l)},`),
                    '}',
                    '',
                    `impl ${name} {`,
                    "    pub fn as_str(self) -> &'static str {",
                    '        match self {',
                    ...lits.map((l) => `            ${name}::${pascal(l)} => ${JSON.stringify(l)},`),
                    '        }',
                    '    }',
                    '}',
                    ''
                );
                return;
            }
            const variants: string[] = [];
            const used = new Set<string>();
            parts.forEach((p, i) => {
                const t = this.gen.mapNode(p, { ...site, key: `${name}#${i}` }, new Map());
                let v = pascal(p.getText().replace(/<.*$/, '').replace(/\[\]$/, 'List'));
                if (used.has(v)) {
                    v = `${v}${i}`;
                }
                used.add(v);
                variants.push(`    ${v}(${render(t, 'elem', this.uses)}),`);
            });
            this.out.push(this.marker(a), '#[derive(Clone)]', `pub enum ${name}${generics} {`, ...variants, '}', '');
            return;
        }
        const t = this.gen.mapNode(a.type, site, new Map());
        const rhs = render(t, 'field', this.uses);
        const code = rhs.replace(/\/\*.*?\*\//g, '');
        const usedTps = tps.filter((tp) => new RegExp(`\\b${tp}\\b`).test(code));
        const g = usedTps.length ? `<${usedTps.join(', ')}>` : '';
        this.out.push(this.marker(a), `pub type ${name}${g} = ${rhs};`, '');
    }

    // ---- anonymous structs ----------------------------------------------------------------

    private emitAnonStructs() {
        const done = new Set<string>();
        for (let round = 0; round < 5; round++) {
            let added = false;
            for (const [key, a] of this.gen.anon) {
                if (a.file !== this.file || done.has(key)) {
                    continue;
                }
                done.add(key);
                added = true;
                const fields: string[] = [];
                if (a.node) {
                    for (const m of a.node.members) {
                        const f = this.field(m, `${a.site}`, false);
                        if (f) {
                            fields.push(f);
                        }
                    }
                } else if (a.type) {
                    for (const p of a.type.getProperties()) {
                        const pt = this.gen.checker.getTypeOfSymbol(p);
                        const t = this.gen.mapType(pt, this.site(`${a.site}.${p.getName()}`), 1);
                        fields.push(`    pub ${fieldName(p.getName())}: ${render(t, 'field', this.uses)},`);
                    }
                }
                this.out.push(`// Inline object type at ${a.site}.`, '#[derive(Clone)]', `pub struct ${a.name} {`, ...fields, '}', '');
            }
            if (!added) {
                break;
            }
        }
    }

    // ---- closure factories ----------------------------------------------------------------
    //
    // docs/evaluator-design.md: a function that builds an object out of nested closures becomes a
    // struct. Its parameters and top-level variables become fields, its nested functions become
    // `&self` methods, and the object it returns is the struct itself.

    factory(f: Factory, fn: ts.FunctionDeclaration, parent: Factory | undefined) {
        const body = fn.body;
        if (!body) {
            return;
        }
        const name = f.name;
        const fields: string[] = [];
        const siteRoot = parent ? `${parent.func}.${f.func.split('.').pop()}` : f.func;
        if (parent) {
            this.uses.add(['jsrt::P']);
            fields.push(`    // The ${parent.name} whose \`${f.func.split('.').pop()}\` built this ${name}.`, `    pub(crate) ${snake(parent.name)}: P<${parent.name}>,`);
        }
        for (const p of fn.parameters) {
            const n = ts.isIdentifier(p.name) ? p.name.text : undefined;
            if (!n || f.dropParams.includes(n)) {
                continue;
            }
            const t = this.gen.mapDecl(p.type, p, this.site(`${siteRoot}.${n}`));
            fields.push(`    ${this.marker(p)}`, `    pub(crate) ${fieldName(n)}: ${renderField(p.questionToken ? opt(t) : t, this.uses, false)},`);
        }
        const methods: ts.FunctionDeclaration[] = [];
        const wrappers: { name: string; target: string; node: ts.Node }[] = [];
        let selfSeen = false;
        let ifaceObject: ts.ObjectLiteralExpression | undefined;
        for (const st of body.statements) {
            if (ts.isFunctionDeclaration(st) && st.name) {
                if (st.body) {
                    methods.push(st);
                }
                continue;
            }
            if (!ts.isVariableStatement(st)) {
                continue;
            }
            const isConst = (st.declarationList.flags & ts.NodeFlags.Const) !== 0;
            for (const d of st.declarationList.declarations) {
                if (!ts.isIdentifier(d.name)) {
                    continue;
                }
                const n = d.name.text;
                const init = d.initializer ? skipParens(d.initializer) : undefined;
                if (f.selfNames.includes(n)) {
                    selfSeen = true;
                    if (init && ts.isObjectLiteralExpression(init)) {
                        ifaceObject = init;
                    }
                    this.uses.add(['jsrt::P', 'std::cell::OnceCell']);
                    fields.push(`    ${this.marker(d)}`, `    // \`${n}\`: the object ${f.func} returns, which is this struct.`, `    pub(crate) ${fieldName(n)}: OnceCell<P<${name}>>,`);
                    continue;
                }
                if (init && ts.isCallExpression(init) && ts.isIdentifier(init.expression) && f.wrappers.includes(init.expression.text)) {
                    const arg = init.arguments[0];
                    if (arg && ts.isIdentifier(arg)) {
                        wrappers.push({ name: n, target: arg.text, node: d });
                    }
                    continue;
                }
                if (init && (ts.isArrowFunction(init) || ts.isFunctionExpression(init))) {
                    fields.push(`    ${this.marker(d)}`, `    // \`${n}\` is a closure; it is the method \`${snake(n)}\`.`);
                    continue;
                }
                const t = this.gen.mapDecl(d.type, d, this.site(`${siteRoot}.${n}`));
                const w = this.gen.writes;
                const reassigned = w.reassigned.has(d) || w.written.has(d);
                const mutated = w.mutated.has(d) || (w.writtenThrough.has(d) && !isCopy(t));
                const later = selfSeen && init !== undefined && refersTo(init, f.selfNames);
                let ty: string;
                if (later) {
                    this.uses.add(['std::cell::OnceCell']);
                    ty = `OnceCell<${render(t, 'field', this.uses)}>`;
                } else {
                    ty = renderField(t, this.uses, !isConst || reassigned || mutated);
                }
                const why = later ? ' Set after the struct exists: its initializer uses the struct.' : '';
                fields.push(`    ${this.marker(d)}${why ? ` ${why.trim()}` : ''}`, `    pub(crate) ${fieldName(n)}: ${ty},`);
            }
        }
        // A factory that returns an object literal directly: `return { createCodeFlowAnalyzer, .. }`.
        if (!ifaceObject) {
            for (const st of body.statements) {
                if (ts.isReturnStatement(st) && st.expression && ts.isObjectLiteralExpression(skipParens(st.expression))) {
                    const e = skipParens(st.expression);
                    ifaceObject = ts.isObjectLiteralExpression(e) ? e : undefined;
                }
            }
        }
        // A nested factory stores a handle to this struct, which `&self` cannot produce: keep one.
        const hasNested = methods.some((m) => this.gen.factoryByFunc.has(`${this.file}:${f.func}.${m.name?.text}`));
        if (hasNested && !selfSeen) {
            this.uses.add(['jsrt::P', 'std::cell::OnceCell']);
            fields.push(`    // This struct's own handle, set once it is in the arena: a nested factory stores it.`, `    pub(crate) handle: OnceCell<P<${name}>>,`);
        }
        if (this.mode === 'stubs' || this.wants(name)) {
            this.out.push(this.marker(fn), `pub struct ${name} {`, ...fields, '}', '');
        }
        if (this.mode === 'deps') {
            for (const m of methods) {
                const nf = this.gen.factoryByFunc.get(`${this.file}:${f.func}.${m.name?.text}`);
                if (nf) {
                    this.factory(nf, m, f);
                }
            }
            return;
        }

        // The factory function itself builds the struct.
        if (!parent) {
            const vis = isExported(fn) ? 'pub ' : 'pub(crate) ';
            const params = fn.parameters.filter((p) => !(ts.isIdentifier(p.name) && f.dropParams.includes(p.name.text)));
            this.uses.add(['jsrt::P']);
            this.out.push(
                ...this.fnStub(
                    {
                        name: f.func,
                        vis,
                        receiver: undefined,
                        decl: fn,
                        site: f.func,
                        outerGenerics: new Set(),
                        body: true,
                        params,
                        doc: [`/// Builds the ${name}. Dropped parameters: ${f.dropParams.join(', ') || 'none'}.`],
                        storesParams: true,
                        noNestedDoc: true,
                    },
                    '',
                    `P<${name}>`
                )
            );
        }

        // Members of the returned object.
        const ifaceMembers = new Set<string>();
        const extraMethods: string[] = [];
        this.currentImpl = name;
        if (ifaceObject) {
            const ifaceDecl = f.iface ? this.gen.decls.get(f.iface)?.find(ts.isInterfaceDeclaration) : undefined;
            for (const prop of ifaceObject.properties) {
                const pname = prop.name ? propName(prop.name) : undefined;
                if (!pname) {
                    continue;
                }
                ifaceMembers.add(pname);
                if (ts.isShorthandPropertyAssignment(prop)) {
                    continue;
                }
                if (ts.isPropertyAssignment(prop)) {
                    const init = skipParens(prop.initializer);
                    if (ts.isIdentifier(init) && init.text === pname) {
                        continue;
                    }
                    const member = ifaceDecl?.members.find((m) => memberName(m) === pname);
                    const sig = member && (ts.isPropertySignature(member) || ts.isMethodSignature(member)) ? member : undefined;
                    if (ts.isIdentifier(init)) {
                        const target = methods.find((m) => m.name?.text === init.text);
                        if (target) {
                            extraMethods.push(
                                ...this.fnStub(
                                    { name: pname, vis: 'pub ', receiver: '&self', decl: target, site: `${siteRoot}.${pname}`, outerGenerics: new Set(), body: true, doc: [`/// \`${pname}\` in the returned object is \`${init.text}\`.`] },
                                    '    '
                                )
                            );
                            continue;
                        }
                    }
                    if (ts.isArrowFunction(init) || ts.isFunctionExpression(init)) {
                        const sigNode = sig && ts.isPropertySignature(sig) && sig.type && ts.isFunctionTypeNode(sig.type) ? sig.type : undefined;
                        extraMethods.push(
                            ...this.fnStub(
                                {
                                    name: pname,
                                    vis: 'pub ',
                                    receiver: '&self',
                                    decl: init,
                                    site: `${siteRoot}.${pname}`,
                                    outerGenerics: new Set(),
                                    body: true,
                                    params: sigNode?.parameters ?? init.parameters,
                                    retNode: sigNode?.type,
                                    doc: [`/// An arrow function in the returned object.`],
                                }
                            , '    ')
                        );
                    }
                }
            }
        }
        const items: string[] = [];
        const nestedFactories: { f: Factory; fn: ts.FunctionDeclaration }[] = [];
        for (const m of methods) {
            const mname = m.name?.text ?? '';
            const vis = ifaceMembers.has(mname) ? 'pub ' : 'pub(crate) ';
            items.push(...this.fnStub({ name: mname, vis, receiver: '&self', decl: m, site: `${siteRoot}.${mname}`, outerGenerics: new Set(), body: true }, '    '));
            const nf = this.gen.factoryByFunc.get(`${this.file}:${f.func}.${mname}`);
            if (nf) {
                nestedFactories.push({ f: nf, fn: m });
            }
        }
        for (const wr of wrappers) {
            const target = methods.find((m) => m.name?.text === wr.target);
            if (target) {
                const vis = ifaceMembers.has(wr.name) ? 'pub ' : 'pub(crate) ';
                items.push(
                    ...this.fnStub(
                        { name: wr.name, vis, receiver: '&self', decl: target, site: `${siteRoot}.${wr.name}`, outerGenerics: new Set(), body: true, doc: [`/// \`${wr.name}\` is \`${wr.target}\` wrapped by a logger; the port calls it directly.`] },
                        '    '
                    ).map((l, i) => (i === 0 ? `    ${this.marker(wr.node)}` : l))
                );
            }
        }
        this.currentImpl = '';
        this.out.push(`impl ${name} {`, ...trimBlank([...items, ...extraMethods]), '}', '');
        for (const nf of nestedFactories) {
            this.factory(nf.f, nf.fn, f);
        }
    }
}

// ---- helpers ------------------------------------------------------------------------------

// A constructor parameter property, or a parameter the body assigns to a property as is
// (`this._x = x`, `entry.x = x`).
function storesParam(decl: ts.SignatureDeclaration, p: ts.ParameterDeclaration): boolean {
    if (ts.isConstructorDeclaration(decl) && ts.isParameterPropertyDeclaration(p, decl)) {
        return true;
    }
    const name = ts.isIdentifier(p.name) ? p.name.text : undefined;
    const body = 'body' in decl && decl.body ? decl.body : undefined;
    if (name === undefined || !body) {
        return false;
    }
    let found = false;
    const visit = (n: ts.Node) => {
        if (found) {
            return;
        }
        if (
            ts.isBinaryExpression(n) &&
            n.operatorToken.kind === ts.SyntaxKind.EqualsToken &&
            (ts.isPropertyAccessExpression(n.left) || ts.isElementAccessExpression(n.left)) &&
            ts.isIdentifier(n.right) &&
            n.right.text === name
        ) {
            found = true;
            return;
        }
        ts.forEachChild(n, visit);
    };
    visit(body);
    return found;
}

function withOwnerArg(t: IR, owner: string): IR {
    const ownerIR: IR = { k: 'raw', text: `&mut ${owner}`, param: `&mut ${owner}`, copy: false, uses: [] };
    if (t.k === 'fn') {
        return { ...t, params: [ownerIR, ...t.params] };
    }
    if (t.k === 'opt' && t.inner.k === 'fn') {
        return { k: 'opt', inner: { ...t.inner, params: [ownerIR, ...t.inner.params] } };
    }
    return t;
}

function isPrivate(n: ts.Node): boolean {
    return (
        hasModifier(n, ts.SyntaxKind.PrivateKeyword) ||
        hasModifier(n, ts.SyntaxKind.ProtectedKeyword) ||
        ((ts.isPropertyDeclaration(n) || ts.isMethodDeclaration(n)) && ts.isPrivateIdentifier(n.name))
    );
}

function ownProps(decl: ts.InterfaceDeclaration): ts.Node[] {
    return decl.members.filter((m) => ts.isPropertySignature(m));
}

function ownFieldNodes(decl: ts.ClassDeclaration): ts.Node[] {
    const out: ts.Node[] = [];
    for (const m of decl.members) {
        if (ts.isPropertyDeclaration(m) && !hasModifier(m, ts.SyntaxKind.StaticKeyword)) {
            out.push(m);
        } else if (ts.isConstructorDeclaration(m)) {
            for (const p of m.parameters) {
                if (ts.isParameterPropertyDeclaration(p, m)) {
                    out.push(p);
                }
            }
        }
    }
    return out;
}

function isOptionalMember(p: ts.Node): boolean {
    return (ts.isPropertyDeclaration(p) || ts.isParameter(p) || ts.isPropertySignature(p)) && p.questionToken !== undefined;
}

function fieldTypeNode(p: ts.Node): ts.TypeNode | undefined {
    if (ts.isPropertyDeclaration(p) || ts.isParameter(p) || ts.isPropertySignature(p)) {
        return p.type;
    }
    return undefined;
}

function accessorType(t: IR, uses: Uses): string {
    const owned = render(t, 'field', uses);
    return isCopy(t) ? owned : `&${owned}`;
}

function trimBlank(lines: string[]): string[] {
    const out = [...lines];
    while (out.length && out[out.length - 1] === '') {
        out.pop();
    }
    return out;
}

function hex(n: number): string {
    const u = n >>> 0;
    return u < 16 ? String(u) : `0x${u.toString(16)}`;
}

function literalOf(e: ts.Expression): string | undefined {
    if (ts.isNumericLiteral(e)) {
        return e.text;
    }
    if (ts.isPrefixUnaryExpression(e) && e.operator === ts.SyntaxKind.MinusToken && ts.isNumericLiteral(e.operand)) {
        return `-${e.operand.text}`;
    }
    if (ts.isStringLiteral(e) || ts.isNoSubstitutionTemplateLiteral(e)) {
        return JSON.stringify(e.text);
    }
    if (e.kind === ts.SyntaxKind.TrueKeyword) {
        return 'true';
    }
    if (e.kind === ts.SyntaxKind.FalseKeyword) {
        return 'false';
    }
    return undefined;
}

function refersTo(node: ts.Node, names: string[]): boolean {
    let found = false;
    const visit = (n: ts.Node) => {
        if (found) {
            return;
        }
        if (ts.isIdentifier(n) && names.includes(n.text)) {
            found = true;
            return;
        }
        ts.forEachChild(n, visit);
    };
    visit(node);
    return found;
}

// Function declarations directly inside a function body, with their lines.
function nestedFunctions(decl: ts.SignatureDeclaration): string[] {
    const out: string[] = [];
    const body = 'body' in decl && decl.body && ts.isBlock(decl.body) ? decl.body : undefined;
    if (!body) {
        return out;
    }
    const visit = (n: ts.Node) => {
        if (ts.isFunctionDeclaration(n) && n.name) {
            out.push(`${n.name.text} (:${lineOf(n)})`);
            return;
        }
        if (ts.isClassDeclaration(n) && n.name) {
            out.push(`class ${n.name.text} (:${lineOf(n)})`);
            return;
        }
        if (ts.isFunctionLike(n)) {
            return;
        }
        ts.forEachChild(n, visit);
    };
    ts.forEachChild(body, visit);
    return out;
}

// `use a::b::{C, D};` per module. Two imports of one name from different modules keep the first
// and comment out the rest; the compile check reports the conflict.
function groupUses(paths: string[]): string[] {
    const byName = new Map<string, string>();
    const byModule = new Map<string, string[]>();
    const out: string[] = [];
    for (const p of paths) {
        const i = p.lastIndexOf('::');
        const mod = p.slice(0, i);
        const name = p.slice(i + 2);
        const prior = byName.get(name);
        if (prior !== undefined && prior !== mod) {
            out.push(`// conflicting import: use ${p};`);
            continue;
        }
        byName.set(name, mod);
        const list = byModule.get(mod) ?? [];
        if (!list.includes(name)) {
            list.push(name);
        }
        byModule.set(mod, list);
    }
    for (const [mod, names] of [...byModule].sort()) {
        names.sort();
        out.push(names.length === 1 ? `use ${mod}::${names[0]};` : `use ${mod}::{${names.join(', ')}};`);
    }
    return out;
}

export function dedupeUses(lines: string[]): string[] {
    // Two imports of one name from different modules: keep the first, qualify nothing. The check
    // reports the conflict.
    const byName = new Map<string, string>();
    const out: string[] = [];
    for (const l of lines) {
        const name = l.replace(/;$/, '').split('::').pop() ?? l;
        if (byName.has(name)) {
            out.push(`// conflicting import: ${l}`);
            continue;
        }
        byName.set(name, l);
        out.push(l);
    }
    return out;
}

