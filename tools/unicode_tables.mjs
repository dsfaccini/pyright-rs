#!/usr/bin/env node
// Converts pyright's parser/unicode.ts tables to crates/pyright/src/parser/unicode.rs.
//
//   node tools/unicode_tables.mjs generate   write unicode.rs from the evaluated unicode.ts
//   node tools/unicode_tables.mjs canonical  print the canonical text of the unicode.ts tables
//
// The unicode.rs test `tables_match_typescript` runs `canonical` and compares it with
// the same text built from the compiled Rust tables.
//
// unicode.ts is evaluated with the TypeScript compiler from the pyright checkout,
// so the Rust tables come from the values, not from parsing the source text.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const pyrightRoot = process.env.PYRIGHT_ROOT ?? join(homedir(), 'pyright');
const unicodeTsPath = join(pyrightRoot, 'packages/pyright-internal/src/parser/unicode.ts');
const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const unicodeRsPath = join(repoRoot, 'crates/pyright/src/parser/unicode.rs');

function loadTables() {
    const require = createRequire(join(pyrightRoot, 'package.json'));
    const ts = require('typescript');
    const source = readFileSync(unicodeTsPath, 'utf8');
    const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
    const module = { exports: {} };
    new Function('module', 'exports', js)(module, module.exports);
    return Object.entries(module.exports);
}

const isSurrogateTable = (table) => !Array.isArray(table);

function rangeText(entry) {
    return Array.isArray(entry) ? `${entry[0]}-${entry[1]}` : `${entry}`;
}

// One line per table: `name=` then entries. A surrogate table lists `high:[entries]`
// in `for...in` order, which is the order `characters.ts` iterates it.
function canonical(tables) {
    const lines = [];
    for (const [name, table] of tables) {
        if (isSurrogateTable(table)) {
            const parts = [];
            for (const high in table) {
                parts.push(`${high}:[${table[high].map(rangeText).join(',')}]`);
            }
            lines.push(`${name}=${parts.join(',')}`);
        } else {
            lines.push(`${name}=${table.map(rangeText).join(',')}`);
        }
    }
    return lines.join('\n') + '\n';
}

function screamingSnake(name) {
    return name.replace(/([a-z])([A-Z])/g, '$1_$2').toUpperCase();
}

function hex(n) {
    return '0x' + n.toString(16).padStart(4, '0');
}

function rustRange(entry) {
    return Array.isArray(entry) ? `R(${hex(entry[0])}, ${hex(entry[1])})` : `S(${hex(entry)})`;
}

function rustEntries(entries, indent) {
    const items = entries.map(rustRange);
    const lines = [];
    for (let i = 0; i < items.length; i += 6) {
        lines.push(indent + items.slice(i, i + 6).join(', ') + ',');
    }
    return lines.join('\n');
}

function lineOf(source, name) {
    const index = source.split('\n').findIndex((line) => line.startsWith(`export const ${name}:`));
    return index + 1;
}

function generate(tables) {
    const source = readFileSync(unicodeTsPath, 'utf8');
    const out = [];
    out.push('//! Port of `packages/pyright-internal/src/parser/unicode.ts`.');
    out.push('//!');
    out.push('//! Generated by `tools/unicode_tables.mjs generate` from the evaluated TypeScript');
    out.push('//! tables. Do not edit by hand. The test below checks the tables against unicode.ts.');
    out.push('');
    out.push('use UnicodeRange::{R, S};');
    out.push('');
    out.push('// parser/unicode.ts:13');
    out.push('#[derive(Clone, Copy, Debug, PartialEq, Eq)]');
    out.push('pub enum UnicodeRange {');
    out.push('    /// `[number, number]`: an inclusive range.');
    out.push('    R(u32, u32),');
    out.push('    /// `number`: a single code.');
    out.push('    S(u32),');
    out.push('}');
    out.push('');
    out.push('// parser/unicode.ts:14');
    out.push('pub type UnicodeRangeTable = &\'static [UnicodeRange];');
    out.push('');
    out.push('/// High surrogate to the table of low surrogates, in `for...in` order.');
    out.push('// parser/unicode.ts:15');
    out.push('pub type UnicodeSurrogateRangeTable = &\'static [(u32, UnicodeRangeTable)];');
    for (const [name, table] of tables) {
        out.push('');
        out.push(`// parser/unicode.ts:${lineOf(source, name)}`);
        if (isSurrogateTable(table)) {
            out.push(`pub const ${screamingSnake(name)}: UnicodeSurrogateRangeTable = &[`);
            for (const high in table) {
                out.push(`    (${hex(Number(high))}, &[`);
                out.push(rustEntries(table[high], '        '));
                out.push('    ]),');
            }
            out.push('];');
        } else {
            out.push(`pub const ${screamingSnake(name)}: UnicodeRangeTable = &[`);
            out.push(rustEntries(table, '    '));
            out.push('];');
        }
    }
    out.push('');
    out.push('#[cfg(test)]');
    out.push('mod tests {');
    out.push('    use super::*;');
    out.push('');
    out.push('    fn range_text(entry: &UnicodeRange) -> String {');
    out.push('        match entry {');
    out.push('            R(a, b) => format!("{a}-{b}"),');
    out.push('            S(a) => format!("{a}"),');
    out.push('        }');
    out.push('    }');
    out.push('');
    out.push('    fn table_text(table: UnicodeRangeTable) -> String {');
    out.push('        table.iter().map(range_text).collect::<Vec<_>>().join(",")');
    out.push('    }');
    out.push('');
    out.push('    fn surrogate_table_text(table: UnicodeSurrogateRangeTable) -> String {');
    out.push('        table');
    out.push('            .iter()');
    out.push('            .map(|(high, ranges)| format!("{high}:[{}]", table_text(ranges)))');
    out.push('            .collect::<Vec<_>>()');
    out.push('            .join(",")');
    out.push('    }');
    out.push('');
    out.push('    /// Rebuilds the canonical text of `tools/unicode_tables.mjs canonical` from the');
    out.push('    /// compiled tables and compares it with the output for the pinned unicode.ts.');
    out.push('    #[test]');
    out.push('    fn tables_match_typescript() {');
    out.push('        let mut rust = String::new();');
    for (const [name, table] of tables) {
        const fn = isSurrogateTable(table) ? 'surrogate_table_text' : 'table_text';
        out.push(`        rust.push_str(&format!("${name}={}\\n", ${fn}(${screamingSnake(name)})));`);
    }
    out.push('');
    out.push('        let tool = concat!(env!("CARGO_MANIFEST_DIR"), "/../../tools/unicode_tables.mjs");');
    out.push('        let output = std::process::Command::new("node")');
    out.push('            .arg(tool)');
    out.push('            .arg("canonical")');
    out.push('            .output()');
    out.push('            .expect("run node tools/unicode_tables.mjs canonical");');
    out.push('        assert!(output.status.success(), "{}", String::from_utf8_lossy(&output.stderr));');
    out.push('        let typescript = String::from_utf8(output.stdout).unwrap();');
    out.push('        assert!(rust == typescript, "unicode.rs differs from unicode.ts; rerun tools/unicode_tables.mjs generate");');
    out.push('    }');
    out.push('}');
    writeFileSync(unicodeRsPath, out.join('\n') + '\n');
    execFileSync('rustfmt', ['--edition', '2024', unicodeRsPath]);
}

const command = process.argv[2];
const tables = loadTables();
if (command === 'generate') {
    generate(tables);
} else if (command === 'canonical') {
    process.stdout.write(canonical(tables));
} else {
    console.error('usage: node tools/unicode_tables.mjs generate|canonical');
    process.exit(2);
}
